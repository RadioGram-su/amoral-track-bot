# ------------------------------------------------------------ примитивы

def arc(cx, cy, rx, ry, a0, a1, n=None):
    if n is None:
        n = max(6, int(abs(a1 - a0) / 9))
    pts = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


def bez(p0, p1, p2, n=12):
    out = []
    for i in range(n + 1):
        t = i / n
        x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0]
        y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]
        out.append((x, y))
    return out


def dot(x, y):
    return [(x, y), (x + 0.04, y + 0.06)]


def S(*parts):
    """Склеивает части (точки и списки точек) в один штрих."""
    out = []
    for p in parts:
        if isinstance(p, list):
            out.extend(p)
        else:
            out.append(p)
    return out


