# ------------------------------------------------------------ дрожание руки

def hnoise(x, seed):
    """Гладкий детерминированный 1D-шум (сумма синусов)."""
    return (math.sin(x * 1.7 + seed * 3.1) * 0.5 + math.sin(x * 3.3 + seed * 1.3) * 0.3
            + math.sin(x * 6.1 + seed * 7.7) * 0.2)


def densify(pts, step=0.35):
    out = [pts[0]]
    for a, b in zip(pts, pts[1:]):
        d = math.dist(a, b)
        n = max(1, int(d / step))
        for i in range(1, n + 1):
            t = i / n
            out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return out


def wobble(strokes, seed, scale_x=1.0, scale_y=1.0, slant=0.06):
    out = []
    for si, st in enumerate(strokes):
        st = densify(st)
        res = []
        for x, y in st:
            # курсивный наклон + дрожание
            x2 = x * scale_x + y * scale_y * slant
            y2 = y * scale_y
            jx = 0.16 * hnoise(y2 * 0.9 + si, seed)
            jy = 0.13 * hnoise(x2 * 0.9 + si * 2.0, seed + 11)
            res.append((x2 + jx, y2 + jy))
        out.append(res)
    return out


def outline(strokes, seed):
    """Штрихи → многоугольник с переменной толщиной (давление маркера)."""
    shapes = []
    for si, st in enumerate(strokes):
        L = len(st)
        if L == 1:
            st = [st[0], (st[0][0] + 0.01, st[0][1])]
            L = 2
        total = sum(math.dist(a, b) for a, b in zip(st, st[1:])) or 0.01
        if total < 0.3:
            shapes.append(Point(st[0]).buffer(RADIUS * 1.25, 16))
            continue
        acc = 0.0
        for i, (a, b) in enumerate(zip(st, st[1:])):
            t = acc / total
            acc += math.dist(a, b)
            # толще в середине, чуть тоньше к концам, плюс случайное давление
            pressure = 0.88 + 0.12 * math.sin(math.pi * min(1.0, t * 1.1)) + 0.07 * hnoise(t * 6 + si, seed + 5)
            r = RADIUS * pressure
            shapes.append(LineString([a, b]).buffer(r, 8, cap_style=1, join_style=1))
    return unary_union(shapes).simplify(0.02)


# ------------------------------------------------------------ сборка TTF

def glyph_name(ch):
    if ch == " ":
        return "space"
    return "uni%04X" % ord(ch)


def poly_to_pen(geom, pen, dx):
    polys = []
    if isinstance(geom, Polygon):
        polys = [geom]
    elif isinstance(geom, MultiPolygon):
        polys = list(geom.geoms)
    else:
        polys = [g for g in getattr(geom, "geoms", []) if isinstance(g, Polygon)]
    for p in polys:
        p = orient(p, sign=-1.0)  # TrueType: внешний контур по часовой
        rings = [p.exterior] + list(p.interiors)
        for ring in rings:
            coords = list(ring.coords)[:-1]
            if len(coords) < 3:
                continue
            pen.moveTo((round((coords[0][0] + dx) * SCALE), round(coords[0][1] * SCALE)))
            for x, y in coords[1:]:
                pen.lineTo((round((x + dx) * SCALE), round(y * SCALE)))
            pen.closePath()


def build():
    cmap = {}
    glyphs = {}
    metrics = {}
    order = [".notdef", "space"]
    # .notdef — пустой квадратик-набросок
    pen = TTGlyphPen(None)
    nd = outline([[(0.5, 0), (5.5, 0), (5.5, 10), (0.5, 10), (0.5, 0)]], 1)
    poly_to_pen(nd, pen, 0.6)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (int(7.2 * SCALE), 0)
    pen = TTGlyphPen(None)
    glyphs["space"] = pen.glyph()
    metrics["space"] = (int(3.6 * SCALE), 0)
    cmap[ord(" ")] = "space"
    cmap[0x00A0] = "space"

    entries = []
    for ch, strokes in G.items():
        entries.append((ch, strokes, 1.0, 1.0))
        low = ch.lower()
        if low != ch and low not in G:
            # капитель: строчная = уменьшенная заглавная
            entries.append((low, strokes, 0.86, 0.74))

    for ch, strokes, sx, sy in entries:
        seed = (ord(ch) * 0.618) % 17
        w = wobble(strokes, seed, sx, sy)
        geom = outline(w, seed)
        minx, miny, maxx, maxy = geom.bounds
        lsb = 0.55
        dx = lsb - minx
        adv = (maxx - minx) + lsb * 2 + 0.55
        name = glyph_name(ch)
        pen = TTGlyphPen(None)
        poly_to_pen(geom, pen, dx)
        glyphs[name] = pen.glyph()
        metrics[name] = (int(round(adv * SCALE)), int(round(lsb * SCALE)))
        cmap[ord(ch)] = name
        order.append(name)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    # пересчёт lsb по фактическим контурам
    glyf = fb.font["glyf"]
    hmtx = {}
    for name in order:
        g = glyf[name]
        g.recalcBounds(glyf)
        lsb = getattr(g, "xMin", 0) if g.numberOfContours else 0
        hmtx[name] = (metrics[name][0], lsb)
    fb.setupHorizontalMetrics(hmtx)
    fb.setupHorizontalHeader(ascent=980, descent=-260)
    fb.setupNameTable({
        "familyName": "Karakulya",
        "styleName": "Regular",
        "uniqueFontIdentifier": "Karakulya-Regular-1.0",
        "fullName": "Karakulya Regular",
        "psName": "Karakulya-Regular",
        "version": "1.0",
        "copyright": "Karakulya — original typeface for the game 'Нарисуй героя'.",
    })
    fb.setupOS2(sTypoAscender=980, sTypoDescender=-260, sTypoLineGap=80,
                usWinAscent=1100, usWinDescent=320, sCapHeight=700, sxHeight=520,
                achVendID="NGRY")
    fb.setupPost()
    fb.setupHead(unitsPerEm=UPM)
    path = os.path.join(OUT, "Karakulya.ttf")
    fb.save(path)
    print("font saved", path, len(order), "glyphs")
    return path


if __name__ == "__main__":
    build()
